#!/usr/bin/env python3
"""Refresh harness model menus from the central router (no upstream requests)."""

import json
import os
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = os.environ.get("MODEL_ROUTER_URL", "http://127.0.0.1:4000").rstrip("/")
KEY = os.environ.get("MODEL_ROUTER_API_KEY", "unused")


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def value(node, default=None):
    result = node.get("value") if isinstance(node, dict) else None
    return default if result is None else result


def main():
    request = urllib.request.Request(
        ORIGIN + "/v1/models", headers={"Authorization": "Bearer " + KEY}
    )
    with urllib.request.urlopen(request, timeout=15) as response:
        models = json.load(response)["data"]
    if not models:
        raise SystemExit("Router returned no models; existing menus were kept.")

    opencode = json.loads((ROOT / "opencode/opencode.json").read_text())
    claude = json.loads((ROOT / "claude/settings.json").read_text())
    claude["modelPicker"]["options"] = [
        {"model": m["id"], "label": m.get("display_name", m["id"]),
         "description": "Model Router"}
        for m in models
    ]
    claude["modelPicker"]["replaceBuiltInOptions"] = True
    opencode["providers"] = {}
    qwen = json.loads((ROOT / "qwen/settings.json").read_text())
    # Match the upstream's native protocol to avoid unnecessary translation.
    qwen["modelProviders"] = {"openai": [], "anthropic": [], "gemini": []}
    # config.yaml uses JSON syntax, a subset of YAML, to avoid a PyYAML dependency.
    mcode = json.loads((ROOT / "mcode/config.yaml").read_text())
    mcode["custom_provider"] = {}
    kimi = ['# Generated by harnesses/shared/sync-router-models.py.',
            'default_model = "model-router/deepseek-v4.1-flash"',
            '', '[thinking]', 'enabled = true', '']
    groups = {
        "model-router": ("Chat", "openai", "openai-completions", "openai-compatible"),
        "model-router-responses": ("Responses", "openai_responses", "openai-responses", "openai"),
        "model-router-anthropic": ("Anthropic", "anthropic", "anthropic-messages", "anthropic"),
    }
    for group, (label, kimi_type, api, package) in groups.items():
        opencode["providers"][group] = {
            "name": f"Model Router ({label})",
            "package": "aisdk:@ai-sdk/" + package,
            "settings": {"baseURL": ORIGIN + "/v1", "apiKey": KEY},
            "models": {},
        }
        mcode["custom_provider"][group] = {
            "name": f"Model Router ({label})", "kind": "custom", "enabled": True,
            "api": api, "options": {"baseURL": ORIGIN + "/v1", "apiKey": KEY,
                                     "authMode": "api-key"}, "models": {},
        }
        kimi += [f'[providers.{group}]', f'type = "{kimi_type}"',
                 'base_url = ' + json.dumps(ORIGIN if kimi_type == "anthropic" else ORIGIN + "/v1"),
                 'api_key_env = "MODEL_ROUTER_API_KEY"', '']

    for model in models:
        mid = model["id"]
        md = model.get("metadata", {})
        caps = md.get("router", {})
        dialect = md.get("dialect", "openai-chat")
        group = {"anthropic": "model-router-anthropic",
                 "openai-responses": "model-router-responses"}.get(dialect, "model-router")
        limits = caps.get("limits", {})
        context = value(limits.get("context_window"), 128000)
        output = value(limits.get("max_output_tokens"), 16384)
        reasoning = value(caps.get("reasoning", {}).get("supported"), False)
        inputs = caps.get("modalities", {}).get("input", {})
        image = value(inputs.get("image"), False)
        entry = {"name": mid, "limit": {"context": context, "output": output}}
        opencode["providers"][group]["models"][mid] = dict(entry)
        mc = dict(entry, reasoning=reasoning)
        mc["capabilities"] = {"support_image": image}
        mcode["custom_provider"][group]["models"][mid] = mc

        qe = {"id": mid, "name": mid + " (Model Router)",
              "baseUrl": ORIGIN if dialect in ("anthropic", "gemini") else ORIGIN + "/v1",
              "envKey": "MODEL_ROUTER_API_KEY",
              "generationConfig": {"customHeaders": {"x-session-id": "${session_id}"},
                                   "contextWindowSize": context}}
        if dialect == "openai-responses":
            qe["wireApi"] = "responses"
        qwen_group = dialect if dialect in ("anthropic", "gemini") else "openai"
        qwen["modelProviders"][qwen_group].append(qe)

        capabilities = ["tool_use"] if value(caps.get("tools", {}).get("supported")) else []
        if reasoning:
            capabilities.append("thinking")
        for modality in ["image", "video", "audio"]:
            if value(inputs.get(modality), False):
                capabilities.append(modality + "_in")
        kimi += [f'[models.{json.dumps(group + "/" + mid)}]',
                 f'provider = "{group}"', 'model = ' + json.dumps(mid),
                 'display_name = ' + json.dumps(mid),
                 f'max_context_size = {context}', f'max_output_size = {output}',
                 'capabilities = ' + json.dumps(capabilities)]
        efforts = value(caps.get("reasoning", {}).get("effort", {}).get("values"))
        if efforts:
            mc["thinking"] = {"effortOptions": efforts,
                              "defaultEffort": "low" if "low" in efforts else efforts[0]}
            mc["thinking_config"] = {"mode": "switchable", "default_value": "true"}
            kimi += ['support_efforts = ' + json.dumps([e for e in efforts if e != "none"])]
            if "none" in efforts:
                kimi += ['off_effort = "none"']
        if dialect == "openai-chat" and reasoning:
            kimi += ['reasoning_key = "reasoning_content"']
        kimi += ['']

    opencode["model"] = "model-router/deepseek-v4.1-flash"
    mcode["defaultModel"] = "custom_provider:model-router/deepseek-v4.1-flash"
    qwen.setdefault("security", {}).setdefault("auth", {})["selectedType"] = "anthropic"
    qwen["model"] = {"name": "qwen3.8-max", "baseUrl": ORIGIN}
    write_json(ROOT / "opencode/opencode.json", opencode)
    write_json(ROOT / "claude/settings.json", claude)
    write_json(ROOT / "qwen/settings.json", qwen)
    write_json(ROOT / "mcode/config.yaml", mcode)
    (ROOT / "kimi-code/config.toml").write_text("\n".join(kimi))
    count = sum(len(p["models"]) for p in opencode["providers"].values())
    print(f"Updated Claude, OpenCode, Qwen, MCode, and Kimi menus: {count} router models each.")


if __name__ == "__main__":
    raise SystemExit("Legacy refresh disabled: it discards audited capability settings. "
                     "Update model entries manually; see harnesses/model-capabilities.md.")
    if KEY != "unused":
        raise SystemExit("This unauthenticated-local setup stores only the public placeholder 'unused'.")
    main()
